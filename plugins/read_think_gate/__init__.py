"""read-think-gate plugin — user-intent and investigation gate.

Externalized from ``agent/read_think_gate.py`` + its ``tool_executor`` /
``agent_init`` wiring (fork narrow-waist rule: capability lives at the edges).
The current behavior contract:

* one ``check_batch`` per assistant_message (the executor's ``pre_tool_batch``
  hook fires exactly once per batch, at the same two dispatch seams the old
  core wiring used);
* reads, analysis, reviews, and plans never authorize a write;
* a write requires an explicit user modification request and a completed
  investigation of the target, its surroundings, tests/config, and verification;
* repeated blocked writes stop and hand the unresolved decision back to the user
  rather than exhausting rounds into an implicit allow;
* four-axis evidence accumulates within a turn and spills to
  ``~/.hermes/cache/four_axis_gate_<pid>_<session>.json`` for the guards plugin's
  second line;
* cron platforms are exempt (unattended jobs cannot answer gate prompts);
* a crashing gate fails CLOSED at the dispatcher (policy hooks fail closed:
  the crash surfaces as a named block directive in the tool result, never a
  silent allow); the emitter itself is still crash-safe — a dispatch failure
  logs a warning, it cannot take the executor down.

The gate instance is per-session (``_GATES`` registry keyed by session_id,
dropped on session end/reset). Config section: ``read_think_gate`` in
config.yaml — the same section the former core init read.
"""

from __future__ import annotations

import contextvars
import json
import logging
from typing import Any, Dict, Optional

from .gate import _STATE_NAMESPACE, ReadThinkGate, ReadThinkGateConfig
from plugins._shared_state import get_session_state

logger = logging.getLogger("plugins.read-think-gate")

# session_id -> gate instance. Cron sessions get an instance with enabled=False,
# mirroring the agent_init exemption the core wiring used to apply.
_GATES: dict[str, ReadThinkGate] = {}
# 网关单进程服务多会话（HX002）：模块级单值会被后启动会话抢占，先启动
# 会话的空 sid 批次落错桶（2026-10-27 反方审查 B1）。ContextVar 按执行
# 上下文隔离——asyncio task/线程各持各的会话 id，互不覆盖。
_ACTIVE_SESSION_ID: contextvars.ContextVar[Optional[str]] = contextvars.ContextVar(
    "rtg_active_session_id", default=None,
)
_INTERNAL_TURN_DISPLAY_KINDS = frozenset(
    {"internal_notification", "process_complete", "async_delegation_complete"}
)

# 网关机器消息兜底标记：这些前缀只由 Hermes 网关生成、以 user-role 载荷
# 送达。turn_display_kind 缺失/未标注时，若不按 internal 处理会走非 internal
# 分支清掉已建立的修改授权（2026-11-09 实测：后台进程退出通知重置了 clarify
# 表单已授予的授权，导致已获用户批准的 patch 连续误拦）。子串匹配（零正则），
# 精确到网关生成的原文片段，普通用户消息不含这些标记。
_GATEWAY_MACHINE_MARKERS = (
    "[INTERNAL NOTIFICATION — generated by the Hermes gateway",
    "[IMPORTANT: Background process ",
    # Synthetic goal/loop turns arrive as plain user-role payloads on the
    # classic CLI (the gateway's local route marks them internal, the REPL
    # path does not). Classifying them as a new human turn revoked the
    # authorization granted by the user's original goal message, so every
    # continuation re-asked for permission and its writes were refused.
    "[Continuing toward your standing goal]",
    "[/loop wakeup #",
)


def _is_gateway_machine_message(message: str | None) -> bool:
    """Whether this user-role payload is Hermes-generated, not human input.

    Covers gateway notices and the synthetic goal/loop continuation turns that
    reach the gate as ordinary user messages on the classic CLI.
    """
    if not message:
        return False
    return any(marker in message for marker in _GATEWAY_MACHINE_MARKERS)


def _config_section() -> dict[str, Any]:
    """Read the ``read_think_gate`` config section; ``{}`` on any failure."""
    try:
        from hermes_cli.config import load_config_readonly

        cfg = load_config_readonly() or {}
        section = cfg.get("read_think_gate")
        return section if isinstance(section, dict) else {}
    except Exception:
        logger.warning("read-think-gate: config read failed; using empty section", exc_info=True)
        return {}


def _gate_for(session_id: str, platform: str) -> ReadThinkGate:
    """Get or create this session's gate, applying the cron exemption.

    Contract:
      Postconditions: never raises; a config failure yields the default
        config, and platform "cron" always yields enabled=False.
    """
    gate = _GATES.get(session_id)
    if gate is not None:
        return gate
    try:
        cfg = ReadThinkGateConfig.from_mapping(_config_section())
    except Exception:
        logger.warning("read-think-gate: config ignored", exc_info=True)
        cfg = ReadThinkGateConfig()
    if platform == "cron":
        import dataclasses as _dc

        cfg = _dc.replace(cfg, enabled=False)
    gate = ReadThinkGate(cfg, session_id=session_id)
    _GATES[session_id] = gate
    return gate


def _current_gate(session_id: str, platform: str) -> Optional[ReadThinkGate]:
    """Resolve the gate this batch belongs to; None when unkeyed (no session)."""
    if not session_id:
        return None
    return _gate_for(session_id, platform)


def effective_session_id(session_id: str = "") -> str:
    """空 session_id 回退到最近 on_session_start 登记的活跃会话。

    写端（pre_tool_batch 扫描→marker 落盘）与读端（guards.four_axis 的
    marker 桶解析）必须共用本函数——任一端单独回退而另一端不回退，两端
    marker 桶必然错配：主防线不扫描 + 副防线照拦的永久拦截形态
    （2026-10-27 审计确认的残留缺陷，four_axis.py 源码注释自认）。

    Contract:
      Postconditions: 恒返回 str；无活跃会话时返回空串（桶归 nosession，
        与既有行为一致）。
    """
    return session_id or _ACTIVE_SESSION_ID.get() or ""


def on_session_start(session_id: str = "", **_kwargs: Any) -> None:
    """Key the active session (turn-scoped state restarts per session)."""
    _ACTIVE_SESSION_ID.set(session_id or None)


def on_session_reset(session_id: str = "", **_kwargs: Any) -> None:
    """Drop the session's gate — next batch builds a fresh one."""
    _GATES.pop(session_id, None)
    get_session_state(session_id, _STATE_NAMESPACE).clear()
    if _ACTIVE_SESSION_ID.get() == (session_id or None):
        _ACTIVE_SESSION_ID.set(None)


def on_session_end(session_id: str = "", **_kwargs: Any) -> None:
    """Drop the session's gate (mirror of reset; either name may fire)."""
    _GATES.pop(session_id, None)
    get_session_state(session_id, _STATE_NAMESPACE).clear()
    if _ACTIVE_SESSION_ID.get() == (session_id or None):
        _ACTIVE_SESSION_ID.set(None)


def _warm_user_side_judge(message: str) -> None:
    """点燃用户侧合并判定（yinyang-restate-guard 的 judge_user_side）。

    为什么从这里点：本插件此刻即将阻塞在一次 LLM 判定上，而这条消息的其他守卫
    （yinyang 的 challenge、scope_gate 的 authorized）用的是同一个合并判定——它们
    每来一条新消息都会判一次，所以这次预热不存在"白判"的情形。合并通道不可用
    （插件未加载/被禁用）时就地放弃。

    Contract:
      Preconditions: message 为非空的当轮用户原话
      Postconditions: 立刻返回；判定在后台线程执行，异常全部吞掉；绝不 raise
    """
    from plugins._judge_warm import warm
    # 运行时插件模块名 = hermes_plugins.<slug>（连字符目录 → 下划线模块名），
    # 与 declare_act_guard → reply-certainty-checker 同一约定；两个命名空间都试。
    try:
        from hermes_plugins.yinyang_restate_guard import judge_user_side
    except ImportError:
        try:
            from plugins.yinyang_restate_guard import judge_user_side
        except ImportError:
            return  # 合并通道不可用（插件未加载）：本轮照旧，只是少了并行
    warm(judge_user_side, message)


def pre_llm_call(
    user_message: str = "",
    session_id: str = "",
    platform: str = "",
    is_first_turn: bool = False,
    conversation_history: list[dict] | None = None,
    turn_display_kind: str = "",
    **_kwargs: Any,
) -> None:
    """Per-turn reset — the turn's user message drives complexity classification.

    The core ``build_turn_context`` used to call ``gate.reset_for_turn(user_message)``
    directly; the hook carries the same payload (user_message + session identity),
    so the gate sees exactly one reset per turn, before the first LLM call fires.
    """
    try:
        message = user_message if isinstance(user_message, str) else str(user_message or "")
        internal = turn_display_kind in _INTERNAL_TURN_DISPLAY_KINDS
        if not internal and _is_gateway_machine_message(message):
            internal = True
        # 本轮马上要做意图判定（~4s）。同一条消息上，其他守卫还要一份用户侧合并判定
        # （challenge/decision/authorized，~2.5s），两者互不依赖——先把那边点燃，
        # 让两次判定并行，本轮只等一次。它们后到时命中判定缓存，不会重复付费。
        # 放在 gate 判空之前：本闸是否对本会话启用，不影响别的守卫是否要判定。
        if not internal and message.strip():
            _warm_user_side_judge(message)
        gate = _current_gate(session_id or _ACTIVE_SESSION_ID.get() or "", platform)
        if gate is None:
            return
        gate.reset_for_turn(
            user_message=message or None,
            conversation_history=conversation_history,
            internal=internal,
        )
    except Exception:
        logger.warning("read-think-gate: reset_for_turn failed", exc_info=True)


def pre_tool_batch(
    assistant_content: str = "",
    tool_calls: Optional[list] = None,
    session_id: str = "",
    platform: str = "",
    **_kwargs: Any,
) -> Optional[dict[str, Any]]:
    """Batch-level gate check; return ``{"action": "block", "message": ...}`` or None.

    Contract:
      Postconditions: a crashing gate RAISES — the dispatcher converts the
        exception into a fail-closed, named block directive (policy hooks
        fail closed; see ``hermes_cli.plugins_dispatch``), so a broken guard
        is visible in the tool result instead of silently allowing writes.
        Only the session-registry lookup itself is guarded (no gate for a
        batch is a legitimate "no decision" state, distinct from a crash).
    """
    gate = _current_gate(effective_session_id(session_id), platform)
    if gate is None:
        return None
    names = [str(tc.get("name") or "") for tc in (tool_calls or []) if isinstance(tc, dict)]
    args = [tc.get("args") for tc in (tool_calls or []) if isinstance(tc, dict)]
    block = gate.check_batch(assistant_content or "", names, tool_args=args)
    if block is None:
        return None
    return {"action": "block", "message": block}


def on_post_tool_call(
    tool_name: str = "",
    result: Any = None,
    session_id: str = "",
    platform: str = "",
    **_kwargs: Any,
) -> None:
    """Feed an answered clarify form back to the gate as user input.

    The clarify result carries the user's own answers (tools/clarify_tool.py
    ``_result`` builds it from the platform callback's form answers), so it is
    authorization-grade input, not model-fabricated tool output. Without this
    hook the turn-open intent snapshot ignored a mid-turn「修」selection and the
    write stayed blocked until a fresh chat message restarted the turn.

    Contract:
      Postconditions: never raises; only ``tool_name == "clarify"`` with an
        ``answered`` response whose ``user_response`` is non-empty reaches the
        gate. Unanswered/skipped/cancelled results, malformed payloads, and
        sessions without a gate are no-ops (logged, not silent).
    """
    if tool_name != "clarify":
        return
    try:
        gate = _current_gate(effective_session_id(session_id), platform)
        if gate is None:
            return
        payload = json.loads(result) if isinstance(result, str) else result
        if not isinstance(payload, dict):
            return
        texts: list[str] = []
        for response in payload.get("responses") or []:
            if not isinstance(response, dict) or response.get("status") != "answered":
                continue
            value = response.get("user_response")
            if isinstance(value, list):
                texts.extend(str(item) for item in value if str(item).strip())
            elif isinstance(value, str) and value.strip():
                texts.append(value)
        if texts:
            gate.note_user_clarification("；".join(texts))
    except Exception:
        logger.warning("read-think-gate: clarify authorization intake failed", exc_info=True)


def register(ctx) -> None:
    """Plugin-loader contract — without this the loader refuses the plugin
    (``Plugin 'read-think-gate' has no register() function``) and the four-axis
    marker writer never runs, deadlocking every write tool behind the guards
    plugin's secondary line.

    Hook names mirror the ``hooks:`` list in plugin.yaml exactly.
    """
    ctx.register_hook("pre_tool_batch", pre_tool_batch)
    ctx.register_hook("pre_llm_call", pre_llm_call)
    ctx.register_hook("post_tool_call", on_post_tool_call)
    ctx.register_hook("on_session_start", on_session_start)
    ctx.register_hook("on_session_reset", on_session_reset)
    ctx.register_hook("on_session_end", on_session_end)
    logger.info("read-think-gate registered (6 hooks)")
